#!/usr/bin/env bash
# Packages the demo app and builds the EC2 user-data that installs it.
#
# The app tarball is content-addressed (app/app-<sha>.tar.gz in the private app
# bucket), so every launch-template version pins one exact build. Uploading is done
# by deploy.sh / update-app.sh; this script only writes local files.
#
# Usage: scripts/build-userdata.sh <alb-dns-name>
# Output: build/app-<sha>.tar.gz, build/app-key.txt, build/user-data.sh, build/user-data.b64
set -euo pipefail
source "$(dirname "$0")/config.sh"

ALB_DNS="${1:-}"
mkdir -p "$BUILD_DIR"
rm -f "$BUILD_DIR"/app-*.tar.gz

TMP_TAR="$BUILD_DIR/app.tar.gz"
tar -C "$PROJECT_DIR/app" --sort=name --mtime='2026-01-01' --owner=0 --group=0 --numeric-owner \
  -cf - server.py static/index.html static/app.css static/app.js | gzip -9 -n > "$TMP_TAR"
SHA="$(sha256sum "$TMP_TAR" | cut -c1-12)"
APP_TAR="$BUILD_DIR/app-$SHA.tar.gz"
mv "$TMP_TAR" "$APP_TAR"
APP_KEY="app/app-$SHA.tar.gz"
echo "$APP_KEY" > "$BUILD_DIR/app-key.txt"

cat > "$BUILD_DIR/user-data.sh" <<EOF
#!/bin/bash
# vm-failure-demo bootstrap (generated by scripts/build-userdata.sh, app build $SHA)
set -euxo pipefail
exec > >(tee -a /var/log/vmfail-bootstrap.log) 2>&1

mkdir -p /opt/vmfail/app
for attempt in 1 2 3 4 5; do
  aws s3api get-object --bucket "$APP_BUCKET" --key "$APP_KEY" --expected-bucket-owner "$ACCOUNT_ID" \\
    --region "$AWS_REGION" /opt/vmfail/app.tar.gz >/dev/null && break
  sleep \$((attempt * 3))
done
tar -xzf /opt/vmfail/app.tar.gz -C /opt/vmfail/app

# boto3 for the read-only AWS state API; prefer a venv, fall back to the distro package.
PY=/usr/bin/python3
if dnf install -y python3-pip && python3 -m venv /opt/vmfail/venv \\
   && /opt/vmfail/venv/bin/pip install --quiet 'boto3==1.42.97'; then
  PY=/opt/vmfail/venv/bin/python
else
  dnf install -y python3-boto3 || echo "boto3 unavailable: /api/state will report an error"
fi

id vmfail >/dev/null 2>&1 || useradd --system --no-create-home --shell /sbin/nologin vmfail

cat > /etc/vmfail.env <<ENV
AWS_REGION=$AWS_REGION
ASG_NAME=$ASG_NAME
TG_NAME=$TG_NAME
ALB_DNS=$ALB_DNS
PORT=$APP_PORT
ENV

cat > /etc/systemd/system/vmfail.service <<UNIT
[Unit]
Description=EC2 failure-recovery demo app
After=network-online.target
Wants=network-online.target

[Service]
EnvironmentFile=/etc/vmfail.env
ExecStart=\$PY /opt/vmfail/app/server.py
User=vmfail
Restart=always
RestartSec=2
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
UNIT

systemctl daemon-reload
systemctl enable --now vmfail.service
EOF

base64 -w0 "$BUILD_DIR/user-data.sh" > "$BUILD_DIR/user-data.b64"
SIZE=$(stat -c %s "$BUILD_DIR/user-data.sh")
(( SIZE < 16384 )) || die "user-data too large ($SIZE bytes)"
log "app build $SHA ($(stat -c %s "$APP_TAR") bytes) -> s3://$APP_BUCKET/$APP_KEY; user-data $SIZE bytes"
